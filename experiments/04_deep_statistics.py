def var_names(key: str) -> list[str]:
    """Column names come from the raw files, so nothing is hard-coded."""
    first = sorted((ROOT / "data" / "raw").glob("*.h5"))[0]
    with h5py.File(first, "r") as f:
        return [x.decode().strip() for x in np.array(f[key]).ravel()]


