# ---------------------------------------------------------------- helpers
def eta_squared(x: pd.Series, groups: pd.Series) -> float:
    """Share of a variable's variance explained by the groups (0 = none, 1 = all)."""
    m = x.mean()
    ss_total = ((x - m) ** 2).sum()
    ss_between = sum(len(v) * (v.mean() - m) ** 2 for _, v in x.groupby(groups))
    return float(ss_between / ss_total) if ss_total > 0 else float("nan")


def psi(ref: np.ndarray, cur: np.ndarray, bins: int = 10) -> float:
    """Population Stability Index. Rule of thumb: <0.1 stable, 0.1-0.2 moderate, >0.2 big shift."""
    edges = np.unique(np.quantile(ref, np.linspace(0, 1, bins + 1)))
    if len(edges) < 3:
        return float("nan")
    edges[0], edges[-1] = -np.inf, np.inf
    r = np.clip(np.histogram(ref, edges)[0] / len(ref), 1e-6, None)
    c = np.clip(np.histogram(cur, edges)[0] / len(cur), 1e-6, None)
    return float(np.sum((c - r) * np.log(c / r)))


def drift_table(ref: pd.DataFrame, cur: pd.DataFrame, features: list[str]) -> pd.DataFrame:
    rows = []
    for col in features:
        a, b = ref[col].to_numpy(), cur[col].to_numpy()
        sd = a.std()
        ks = stats.ks_2samp(a, b)
        rows.append({
            "feature": col,
            "KS_stat": ks.statistic,
            "KS_p": ks.pvalue,
            "PSI": psi(a, b),
            "wasserstein_in_std": stats.wasserstein_distance(a, b) / sd if sd > 0 else np.nan,
            "mean_shift_in_std": (b.mean() - a.mean()) / sd if sd > 0 else np.nan,
        })
    return pd.DataFrame(rows).set_index("feature")


def share_drifted(dt: pd.DataFrame) -> pd.Series:
    return pd.Series({
        "features": len(dt),
        "share KS p<0.05": round((dt["KS_p"] < 0.05).mean(), 3),
        "share PSI>0.2": round((dt["PSI"] > 0.2).mean(), 3),
    })


