# ================================================================ 5. wear signal
section("5. How strongly do sensors show wear?",
        "Three versions of each sensor's per-flight average:\n"
        "- **raw**: as measured\n"
        "- **delta**: minus the engine's own first-5-flights average (its healthy baseline)\n"
        "- **residual**: minus what a linear 'healthy engine' model predicts from the flight conditions "
        "(fit on healthy flights of dev engines only)\n\n"
        "`rho_pooled` = Spearman correlation with RUL across all flights of all engines. "
        "`rho_within` = the same, computed inside each engine and averaged. "
        "`snr` = (change from the first 20% to the last 10% of life) / (flight-to-flight noise in the "
        "first 20%), median over engines. Bigger = easier to see wear. "
        "W variables are included as a control: they are flight conditions and should show ~no wear.")

fl = fl.sort_values(["file", "split", "unit", "cycle"]).reset_index(drop=True)
eng = fl.groupby(["file", "split", "unit"])
conds = ["alt_mean", "Mach_mean", "TRA_mean", "T2_mean", "alt_max", "TRA_max", "duration_s"]
conds = [c for c in conds if c in fl.columns]
healthy_dev = (fl["split"] == "dev") & (fl["hs"] == 1)
Xc = np.column_stack([np.ones(len(fl)), fl[conds].to_numpy()])

rows = []
for v in INPUTS:
    raw = fl[f"{v}_mean"]
    delta = raw - eng[f"{v}_mean"].transform(lambda s: s.iloc[:5].mean())
    coef, *_ = np.linalg.lstsq(Xc[healthy_dev.to_numpy()], raw[healthy_dev].to_numpy(), rcond=None)
    resid = raw - Xc @ coef
    versions = {"raw": raw, "delta": delta, "resid": resid}
    row = {"variable": v, "group": "W" if v in W else "X_s"}
    for name, s in versions.items():
        row[f"rho_pooled_{name}"] = stats.spearmanr(s, fl["RUL"]).statistic
    for name in ("raw", "resid"):
        s = versions[name]
        within, snrs = [], []
        for _, idx in eng.groups.items():
            x, y = s.loc[idx].to_numpy(), fl.loc[idx, "RUL"].to_numpy()
            n = len(x)
            if n < 20 or np.std(x) == 0:
                continue
            within.append(stats.spearmanr(x, y).statistic)
            early, late = x[: int(0.2 * n)], x[-max(1, int(0.1 * n)):]
            if early.std() > 0:
                snrs.append(abs(late.mean() - early.mean()) / early.std())
        row[f"rho_within_{name}"] = np.nanmean(within)
        row[f"snr_{name}"] = np.nanmedian(snrs)
    rows.append(row)
wear = pd.DataFrame(rows).set_index(["group", "variable"])
table(wear.round(2).sort_values("snr_resid", ascending=False))
best = wear.xs("X_s", level="group")["snr_resid"].idxmax()
report.append(f"Sensor with the clearest wear signal after removing flight conditions: **{best}**.\n")

# example engines: best sensor, raw vs residual, one engine per class
raw = fl[f"{best}_mean"]
coef, *_ = np.linalg.lstsq(Xc[healthy_dev.to_numpy()], raw[healthy_dev].to_numpy(), rcond=None)
fl["_resid"] = raw - Xc @ coef
fig, axes = plt.subplots(2, 3, figsize=(15, 7), sharex="col")
for j, c in enumerate(ORDER):
    pick = units[(units["class"] == c) & (units["split"] == "dev")].iloc[0]
    e = fl[(fl["file"] == pick["file"]) & (fl["split"] == "dev") & (fl["unit"] == pick["unit"])]
    axes[0, j].plot(e["cycle"], e[f"{best}_mean"])
    axes[0, j].set_title(f"{c}: {pick['file']} unit {pick['unit']} - raw {best}")
    axes[1, j].plot(e["cycle"], e["_resid"])
    axes[1, j].set_title("after removing flight conditions")
    fault = pick["fault_starts_at"]
    if pd.notna(fault):
        for ax in axes[:, j]:
            ax.axvline(fault, color="red", ls="--", lw=1)
    axes[1, j].set_xlabel("flight number")
figure("wear_example.png", f"{best}: raw per-flight average (top) vs flight-condition-corrected (bottom). "
                           "Red line = fault starts")
fl = fl.drop(columns="_resid")

